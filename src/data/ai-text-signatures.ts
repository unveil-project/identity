/**
 * Lines where a post says an AI tool wrote it: a footer like "🤖 Generated
 * with Claude Code", or a git-style trailer like "Co-authored-by: Claude".
 * The line must start with these words. A sentence that only talks about a
 * footer ("I removed the Generated with Claude Code line") does not count.
 */

/** Names of AI tools as people write them in a footer or trailer. */
const AI_TOOL =
	"claude(?:[ -]code)?|codex|(?:github[ -])?copilot|cursor|devin|aider|gemini(?:[ -]cli)?|jules|windsurf|cline|roo[ -]?code|openhands|kiro|junie|opencode|chatgpt|gpt-?[\\d.]+o?|an? (?:llm|ai agent|ai model|ai assistant|agent|language model)";

/** Words that may follow a tool name. Any other capitalized word means a person ("Claude Martin"). */
const AFTER_TOOL_OK = new Set([
	"code",
	"opus",
	"sonnet",
	"haiku",
	"fable",
	"ai",
	"cli",
	"app",
	"agent",
	"pro",
	"flash",
	"max",
]);

/** Markup allowed at the start of a line: quote, list, emphasis, <sub>, robot emoji, a "Disclaimer:" label. */
const LEAD =
	"^[ \\t]*(?:>[ \\t]*)*(?:[-*][ \\t]+)?(?:<sub>|<small>|<i>|[_*(\\[])*[ \\t]*(?:🤖[ \\t]*)?(?:[_*]+[ \\t]*)?(?:(?:\\*\\*)?(?:disclaimer|disclosure|ai disclosure|note)(?:\\*\\*)?:?(?:\\*\\*)?[ \\t]+)?";

/** "This comment was ", "The review has been ". */
const SUBJECT =
	"(?:(?:this|the)[ \\t]+(?:comment|review|reply|issue|pr|pull request|response|summary|description|analysis|report|message|triage)[ \\t]+(?:was|has been|is)[ \\t]+)?";

/** "generated", "written", "investigated and written". */
const VERB =
	"(?:[a-z]+[ \\t]+and[ \\t]+)?(?:auto-?)?(?:generated|written|drafted|posted|prepared|authored|addressed|replied|composed|produced)(?:[ \\t]+and[ \\t]+[a-z]+)?";

/** " with ", " by ", " with the help of ", " mostly using ". */
const LINK =
	"[ \\t]+(?:(?:entirely|mostly|largely|partly)[ \\t]+)?(?:with(?:[ \\t]+the)?(?:[ \\t]+help(?:[ \\t]+of|[ \\t]+from))?|by|using|via)[ \\t]+(?:the[ \\t]+)?\\[?";

/**
 * Each pattern ends with a group that holds the words after the tool name,
 * so we can tell a tool from a person with the same name.
 */
export const AI_TEXT_SIGNATURES: readonly { id: string; pattern: RegExp }[] = [
	// "🤖 Generated with [Claude Code](...)", "This review was generated by GitHub Copilot."
	{
		id: "attribution",
		pattern: new RegExp(
			`${LEAD}${SUBJECT}${VERB}${LINK}(${AI_TOOL})\\b(.{0,20})`,
			"gim",
		),
	},
	// "Co-authored-by: Claude <noreply@anthropic.com>", "Drafted-by: Kiro (...)"
	{
		id: "trailer",
		pattern: new RegExp(
			`^[ \\t]*(?:co-authored|drafted|generated|assisted|written|authored)-by:[ \\t]*\\[?(${AI_TOOL})\\b(.{0,20})`,
			"gim",
		),
	},
	// "Written with the help of AI.", "Prepared with AI assistance.", "AI-generated CI triage"
	{
		id: "generic-ai",
		pattern: new RegExp(
			`${LEAD}(?:${SUBJECT}${VERB}[ \\t]+(?:with|by)[ \\t]+(?:the[ \\t]+help[ \\t]+of[ \\t]+)?(?:an[ \\t]+)?(ai)(?:[ \\t]+(?:assistance|help))?(?=[ \\t]*[.,;:)\\]*_<]|[ \\t]*$)|(ai)-generated\\b)()`,
			"gim",
		),
	},
];

/**
 * Footers and trailers are short lines. Longer lines are prose or code.
 * Skipping them also keeps the patterns fast on very long lines.
 */
const MAX_SIGNATURE_LINE = 200;

/** "Claude Martin" is a person: a tool name followed by another capitalized name. */
function looksLikePersonName(afterTool: string): boolean {
	const next = afterTool.match(/^[ \t]+([A-Z][a-z]+)/)?.[1];

	return next !== undefined && !AFTER_TOOL_OK.has(next.toLowerCase());
}

function shortLinesOf(text: string): string {
	return text
		.split("\n")
		.filter((line) => line.length <= MAX_SIGNATURE_LINE)
		.join("\n");
}

function namesAnAITool(pattern: RegExp, text: string): boolean {
	for (const match of text.matchAll(pattern)) {
		const afterTool = match[match.length - 1] ?? "";
		if (!looksLikePersonName(afterTool)) {
			return true;
		}
	}

	return false;
}

/** The ids of the signatures a post's text matches. Empty when none. */
export function aiTextSignaturesOf(text: string): string[] {
	const lines = shortLinesOf(text);

	return AI_TEXT_SIGNATURES.filter(({ pattern }) =>
		namesAnAITool(pattern, lines),
	).map(({ id }) => id);
}
